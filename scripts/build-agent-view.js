#!/usr/bin/env node
/**
 * Render the HTML agent view served at /?mode=agent.
 *
 * Reads:  agent/mode.json, discovery/openapi.json
 * Writes: agent/mode.html
 *
 * Flags:  --check   exit 1 if agent/mode.html is stale (writes nothing)
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const MODE = path.join(ROOT, "agent/mode.json");
const OPENAPI = path.join(ROOT, "discovery/openapi.json");
const OUT = path.join(ROOT, "agent/mode.html");
const ORIGIN = "https://life.ayushrai.site";

function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function link(href, text) {
  return `<a href="${esc(href)}">${esc(text || href)}</a>`;
}

/** Escape text and turn bare https URLs into links. */
function linkify(text) {
  return esc(text).replace(/https:\/\/[^\s<"')]+/g, (url) => {
    const clean = url.replace(/[.,;]+$/, "");
    const tail = url.slice(clean.length);
    return `<a href="${clean}">${clean}</a>${tail}`;
  });
}

function definitionList(entries) {
  const rows = entries
    .map(([key, value]) => `      <dt>${esc(key.replace(/_/g, " "))}</dt>\n      <dd>${linkify(Array.isArray(value) ? value.join("; ") : value)}</dd>`)
    .join("\n");
  return `    <dl>\n${rows}\n    </dl>`;
}

function endpointRows(openapi) {
  const rows = [];
  for (const [route, ops] of Object.entries(openapi.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      if (!op || typeof op !== "object" || !op.operationId) continue;
      const url = `${ORIGIN}${route}`;
      const target = route.includes("{") ? esc(route) : link(url, route);
      const codes = Object.keys(op.responses || {}).join(", ");
      rows.push(
        `        <tr><td>${method.toUpperCase()}</td><td>${target}</td><td>${esc(op.summary || "")}</td><td>${esc(codes)}</td></tr>`
      );
    }
  }
  return rows.join("\n");
}

function render(mode, openapi) {
  const q = mode.quickstart;
  const nav = [
    [`${ORIGIN}/`, "Homepage"],
    [`${ORIGIN}/llms.txt`, "llms.txt"],
    [`${ORIGIN}/developers`, "Developer portal"],
    [`${ORIGIN}/openapi.json`, "OpenAPI spec"],
    [`${ORIGIN}/auth.md`, "Auth guide"],
    [`${ORIGIN}/api/v1/sandbox`, "Sandbox (no auth)"],
    [`${ORIGIN}/api/v1/jobs`, "Async jobs API"],
    [`${ORIGIN}/mcp`, "MCP servers"],
    [`${ORIGIN}/skills.md`, "Agent skills"],
    [`${ORIGIN}/pricing.md`, "Pricing"],
    [`${ORIGIN}/developers/deprecation`, "Versioning and deprecation policy"],
    [`${ORIGIN}/sites/contact`, "Contact"],
    [`${ORIGIN}/privacy`, "Privacy"],
    [mode.formats.json, "This view as JSON"],
  ];

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <!-- Generated by scripts/build-agent-view.js from agent/mode.json and discovery/openapi.json. Do not edit. -->
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Agent view: life.ayushrai.site (Ayush Rai)</title>
  <meta name="description" content="${esc(mode.description)}">
  <meta name="robots" content="noindex, follow">
  <link rel="canonical" href="${ORIGIN}/">
  <link rel="alternate" type="application/json" href="${esc(mode.formats.json)}">
  <link rel="alternate" type="text/markdown" href="${ORIGIN}/index.md">
  <link rel="service-desc" type="application/openapi+json" href="${ORIGIN}/openapi.json">
  <link rel="icon" href="/assets/icons/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="/styles/site.css?v=20261016">
</head>
<body>
  <main id="content" class="page knowledge-page">
    <h1>Agent view: life.ayushrai.site</h1>
    <p class="tagline">${linkify(mode.description)}</p>
    <p>${linkify(mode.when_to_use)}</p>

    <nav aria-label="Agent navigation">
      <ul class="related-links">
${nav.map(([href, text]) => `        <li>${link(href, text)}</li>`).join("\n")}
      </ul>
    </nav>

    <h2 id="quickstart">Quickstart</h2>
${definitionList(Object.entries(q))}

    <h2 id="endpoints">API endpoints</h2>
    <p>Base URL ${link(ORIGIN)}. Contract: ${link(`${ORIGIN}/openapi.json`)}.</p>
    <table>
      <thead><tr><th>Method</th><th>Path</th><th>Purpose</th><th>Responses</th></tr></thead>
      <tbody>
${endpointRows(openapi)}
      </tbody>
    </table>

    <h2 id="authentication">Authentication</h2>
${definitionList(Object.entries(mode.authentication).filter(([key]) => key !== "www_authenticate"))}

    <h2 id="limits">Pricing, limits, and versioning</h2>
${definitionList([
  ["pricing", `${mode.pricing.model}; signup required: ${mode.pricing.signup_required ? "yes" : "no"}; ${mode.pricing.url}`],
  ["rate limit", `${mode.rate_limits.limit} requests per ${mode.rate_limits.window}; headers ${mode.rate_limits.headers.join(", ")}`],
  ["versioning", `${mode.versioning.scheme} (${mode.versioning.current}); policy ${mode.versioning.deprecation_policy}`],
  ["errors", `JSON with error.code, error.message, error.status, error.hint; ${mode.errors.example}`],
])}

    <h2 id="mcp">MCP servers</h2>
${definitionList(Object.entries(mode.mcp))}

    <h2 id="sdk">SDK and CLI</h2>
${definitionList(Object.entries(mode.sdk))}

    <h2 id="skills">Agent skills</h2>
${definitionList([
  ["install", mode.skills.install],
  ["listing", mode.skills.skills_sh],
  ["index", mode.skills.index],
  ["skills", mode.skills.names],
])}

    <h2 id="capabilities">Capabilities</h2>
    <ul>
${mode.capabilities.map((item) => `      <li>${esc(item)}</li>`).join("\n")}
    </ul>
  </main>
</body>
</html>
`;
}

function main() {
  const mode = JSON.parse(fs.readFileSync(MODE, "utf8"));
  const openapi = JSON.parse(fs.readFileSync(OPENAPI, "utf8"));
  const html = render(mode, openapi);
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== html) {
      console.error("agent/mode.html is out of date. Run: npm run build:agent-view");
      process.exit(1);
    }
    console.log("agent/mode.html is up to date.");
    return;
  }
  fs.writeFileSync(OUT, html, "utf8");
  console.log("Wrote agent/mode.html");
}

main();
